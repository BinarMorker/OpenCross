const BgmEntry* bgm_entry(int song_id) {
  return song_id >= 0 && song_id < kBgmSongCount ? &kTable[song_id] : nullptr;
}

const BgmEntry* bgm_entry_by_file(int file_no) {
  for (const auto& entry : kTable)
    if (entry.file_no == file_no) return &entry;
  return nullptr;
}

std::string bgm_path(int file_no) {
  char buf[48];
  std::snprintf(buf, sizeof buf, "cdrom/sound/bgm/BGM%03d.sab", file_no);
  return buf;
}

