<#
.SYNOPSIS
  Installs and launches DuckStation (PS1 emulator) as the behaviour reference for OpenCross.

.DESCRIPTION
  -Setup     Download the latest stable stenzek/duckstation Windows x64 release into tools\duckstation\
             and enable portable mode (portable.txt), so settings, saves and screenshots stay in that folder.
  -Settings  Write/merge tools\duckstation\settings.ini with the comparison settings (native resolution,
             no enhancements, GDB server on 2345, interpreter, uncompressed states, F10/F2/F12 hotkeys, muted). Keys not listed here are left untouched.
  -Run       Launch a disc image (-Image) in batch/no-GUI mode, optionally from a save state (-State).

  DuckStation also needs a PS1 BIOS dump in tools\duckstation\bios\ and your own disc image of the game.
  Neither is provided by this repository.

.EXAMPLE
  .\tools\duckstation.ps1 -Setup -Settings
  .\tools\duckstation.ps1 -Run -Image D:\games\ChronoCross.cue
  .\tools\duckstation.ps1 -Run -Image D:\games\ChronoCross.cue -State C:\states\field.sav -Fullscreen
#>
[CmdletBinding()]
param(
    [switch]$Setup,
    [switch]$Run,
    [switch]$Settings,
    [switch]$Force,
    [string]$Image,
    [string]$State,
    [switch]$Fullscreen
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$dsDir = Join-Path $PSScriptRoot 'duckstation'
$tmpDir = Join-Path $root 'tmp'

function Find-DuckExe {
    if (-not (Test-Path -LiteralPath $dsDir)) { return $null }
    $exe = Get-ChildItem -LiteralPath $dsDir -Filter 'duckstation-qt*.exe' -File -ErrorAction SilentlyContinue |
        Select-Object -First 1
    if ($exe) { return $exe.FullName }
    return $null
}

function Invoke-Setup {
    $exe = Find-DuckExe
    if ($exe -and -not $Force) {
        Write-Host "DuckStation already installed: $exe (use -Force to reinstall)"
        return
    }
    [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
    $ProgressPreference = 'SilentlyContinue'
    $headers = @{ 'User-Agent' = 'OpenCross-tools' }
    $rel = Invoke-RestMethod -Uri 'https://api.github.com/repos/stenzek/duckstation/releases/latest' -Headers $headers
    $asset = $rel.assets | Where-Object { $_.name -eq 'duckstation-windows-x64-release.zip' } | Select-Object -First 1
    if (-not $asset) {
        $asset = $rel.assets | Where-Object { $_.name -match 'windows-x64.*\.zip$' -and $_.name -notmatch 'sse2|symbols' } |
            Select-Object -First 1
    }
    if (-not $asset) { throw 'No Windows x64 zip asset found in the latest DuckStation release.' }
    Write-Host "Release '$($rel.tag_name)': $($asset.name) ($([math]::Round($asset.size / 1MB, 1)) MB)"

    New-Item -ItemType Directory -Force -Path $tmpDir | Out-Null
    $zip = Join-Path $tmpDir $asset.name
    Invoke-WebRequest -Uri $asset.browser_download_url -OutFile $zip -UseBasicParsing -Headers $headers

    New-Item -ItemType Directory -Force -Path $dsDir | Out-Null
    Expand-Archive -LiteralPath $zip -DestinationPath $dsDir -Force
    Remove-Item -LiteralPath $zip -Force

    # Portable mode: settings.ini, savestates, screenshots and bios live next to the exe.
    Set-Content -LiteralPath (Join-Path $dsDir 'portable.txt') -Value 'portable' -Encoding ASCII
    New-Item -ItemType Directory -Force -Path (Join-Path $dsDir 'bios') | Out-Null
    New-Item -ItemType Directory -Force -Path (Join-Path $dsDir 'games') | Out-Null

    $exe = Find-DuckExe
    if (-not $exe) { throw 'Extraction finished but no duckstation-qt*.exe was found.' }
    Write-Host "Installed: $exe"
    Write-Host "Put a PS1 BIOS dump (from a console you own) into: $(Join-Path $dsDir 'bios')"
    Write-Host "Put your disc images (Chrono Cross (Japan) Disc 1 and Disc 2, .cue+.bin or .chd, names containing Disc 1 / Disc 2) into: $(Join-Path $dsDir 'games')"
}

# Settings applied for 1:1 comparison with OpenCross Classic mode. Key names were taken from a
# settings.ini generated by DuckStation itself; values are enum names found in its binary.
$comparison = [ordered]@{
    'Main' = [ordered]@{
        'ConfirmPowerOff'       = 'false'
        'SaveStateOnExit'       = 'false'
        'PauseOnFocusLoss'      = 'false'
        'StartFullscreen'       = 'false'
        'EmulationSpeed'        = '1'
        'SyncToHostRefreshRate' = 'false'
        'SaveStateCompression'  = 'Uncompressed'
        'SetupWizardIncomplete' = 'false'
    }
    'AutoUpdater' = [ordered]@{ 'CheckAtStartup' = 'false' }
    'GPU' = [ordered]@{
        'Renderer'            = 'Software'
        'ResolutionScale'     = '1'
        'PGXPEnable'          = 'false'
        'TextureFilter'       = 'Nearest'
        'SpriteTextureFilter' = 'Nearest'
        'DitheringMode'       = 'Unscaled'
        'WidescreenHack'      = 'false'
        'ForceVideoTiming'    = 'Disabled'
    }
    'Display' = [ordered]@{
        'AspectRatio'     = 'Auto (Game Native)'
        'Scaling'         = 'NearestInteger'
        'ShowFPS'         = 'true'
        'ShowFrameNumber' = 'true'
        'ScreenshotMode'  = 'InternalResolution'
    }
    'CDROM' = [ordered]@{
        'ReadSpeedup' = '1'
        'SeekSpeedup' = '1'
    }
    'Debug'        = [ordered]@{ 'EnableGDBServer' = 'true'; 'GDBServerPort' = '2345' }
    'CPU'          = [ordered]@{ 'ExecutionMode' = 'Interpreter' }
    'Hotkeys'      = [ordered]@{ 'Screenshot' = 'F10'; 'SaveSelectedSaveState' = 'F2'; 'ToggleAudioCapture' = 'F12' }
    'MediaCapture' = [ordered]@{ 'AudioContainer' = 'wav'; 'AudioCodec' = 'pcm' }
    'MemoryCards'  = [ordered]@{ 'Card1Type' = 'PerGame' }
    'Audio'        = [ordered]@{ 'OutputMuted' = 'true' }
    'Logging'      = [ordered]@{ 'LogToFile' = 'true' }
}

function Invoke-Settings {
    New-Item -ItemType Directory -Force -Path $dsDir | Out-Null
    $path = Join-Path $dsDir 'settings.ini'
    $lines = New-Object System.Collections.Generic.List[string]
    if (Test-Path -LiteralPath $path) { foreach ($l in (Get-Content -LiteralPath $path)) { $lines.Add($l) } }

    foreach ($section in $comparison.Keys) {
        $start = -1
        for ($i = 0; $i -lt $lines.Count; $i++) {
            if ($lines[$i].Trim() -eq "[$section]") { $start = $i; break }
        }
        if ($start -lt 0) {
            if ($lines.Count -gt 0 -and $lines[$lines.Count - 1].Trim() -ne '') { $lines.Add('') }
            $lines.Add("[$section]")
            $start = $lines.Count - 1
        }
        foreach ($key in $comparison[$section].Keys) {
            $val = $comparison[$section][$key]
            $end = $start + 1
            while ($end -lt $lines.Count -and $lines[$end].Trim() -notmatch '^\[') { $end++ }
            $found = $false
            for ($i = $start + 1; $i -lt $end; $i++) {
                if ($lines[$i] -match '^\s*([^=\s]+)\s*=') {
                    if ($Matches[1] -eq $key) { $lines[$i] = "$key = $val"; $found = $true; break }
                }
            }
            if (-not $found) {
                # insert before the section's trailing blank lines
                $ins = $end
                while ($ins -gt $start + 1 -and $lines[$ins - 1].Trim() -eq '') { $ins-- }
                $lines.Insert($ins, "$key = $val")
            }
        }
    }
    [IO.File]::WriteAllLines($path, $lines.ToArray(), (New-Object Text.UTF8Encoding($false)))
    Write-Host "Wrote comparison settings to $path"
}

function Invoke-Run {
    $exe = Find-DuckExe
    if (-not $exe) { throw 'DuckStation is not installed. Run: .\tools\duckstation.ps1 -Setup' }
    if (-not $Image -and -not $State) { throw '-Run needs -Image <disc image> (or -State <save state>).' }
    $argList = New-Object System.Collections.Generic.List[string]
    $argList.Add('-batch')
    $argList.Add('-nogui')
    if ($Fullscreen) { $argList.Add('-fullscreen') } else { $argList.Add('-nofullscreen') }
    if ($State) {
        if (-not (Test-Path -LiteralPath $State)) { throw "Save state not found: $State" }
        $argList.Add('-statefile')
        $argList.Add((Resolve-Path -LiteralPath $State).Path)
    }
    if ($Image) {
        if (-not (Test-Path -LiteralPath $Image)) { throw "Disc image not found: $Image" }
        $argList.Add('-fastboot')
        $argList.Add('--')
        $argList.Add((Resolve-Path -LiteralPath $Image).Path)
    }
    # Quote every argument so paths with spaces survive Start-Process.
    $quoted = ($argList | ForEach-Object { '"' + $_ + '"' }) -join ' '
    Write-Host "$exe $quoted"
    Start-Process -FilePath $exe -ArgumentList $quoted -WorkingDirectory (Split-Path -Parent $exe)
}

if (-not ($Setup -or $Run -or $Settings)) {
    Get-Help $MyInvocation.MyCommand.Path -Detailed
    return
}
if ($Setup) { Invoke-Setup }
if ($Settings) { Invoke-Settings }
if ($Run) { Invoke-Run }
